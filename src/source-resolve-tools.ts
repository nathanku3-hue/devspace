import { registerAppTool } from "@modelcontextprotocol/ext-apps/server";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import * as z from "zod/v4";
import {
  HEX_64_PATTERN,
  resolvedSourceSchema,
  SourceResolveController,
} from "./source-resolve.js";

const NO_APP_META = { _meta: {} } as const;

export function registerSourceResolveTools(input: {
  server: McpServer;
  controller: SourceResolveController;
}): void {
  const { server, controller } = input;

  registerAppTool(
    server,
    "source_resolve_start",
    {
      title: "Start canonical source resolution",
      description:
        "SOURCE-RESOLVE-1 only. Starts one bounded web source resolution session for a given stock ticker. Generates a one-time challenge and launches a fresh ChatGPT Web conversation. The model is permitted to search the web to return 2-4 substantive, canonical publisher or investor-relations URLs (prohibiting Google search redirect shells).",
      inputSchema: {
        ticker: z
          .string()
          .min(1)
          .max(20)
          .describe("Stock ticker symbol to resolve (e.g. SPCX, VICR, DELL)."),
        companyName: z
          .string()
          .optional()
          .describe("Optional company name to narrow search precision."),
        asOfDate: z
          .string()
          .optional()
          .describe("Prospective cutoff date string (e.g. 2026-09-28)."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: true,
      },
    },
    async ({ ticker, companyName, asOfDate }) => {
      const acknowledgement = await controller.startResolve({
        ticker,
        companyName,
        asOfDate,
      });
      return {
        content: [
          {
            type: "text" as const,
            text: `SOURCE-RESOLVE-1 started for ${ticker}. Use source_resolve_status with returned resolveId.`,
          },
        ],
        structuredContent: acknowledgement,
      };
    },
  );

  registerAppTool(
    server,
    "source_resolve_submit",
    {
      title: "Submit canonical source resolution result",
      description:
        "SOURCE-RESOLVE-1 only. Invoked exactly once by the launched ChatGPT Web conversation with one-time challenge. Server validates the challenge, rejects replays, validates that returned URLs are direct canonical sources (rejecting search engine redirects), and retains structured sources.",
      inputSchema: {
        challenge: z
          .string()
          .regex(HEX_64_PATTERN)
          .describe("One-time 64-hex challenge generated by source_resolve_start."),
        ticker: z.string().min(1).max(20).describe("Ticker symbol being resolved."),
        sources: z
          .array(resolvedSourceSchema)
          .min(1)
          .max(10)
          .describe("Array of 2-4 canonical, direct substantive sources with rationale."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: false,
      },
    },
    async ({ challenge, ticker, sources }) => {
      const acknowledgement = controller.submitResolve({
        challenge,
        ticker,
        sources,
      });
      return {
        content: [
          {
            type: "text" as const,
            text: `SOURCE-RESOLVE-1 sources submitted successfully for ${ticker} (${acknowledgement.resolveId}).`,
          },
        ],
        structuredContent: acknowledgement,
      };
    },
  );

  registerAppTool(
    server,
    "source_resolve_status",
    {
      title: "Query canonical source resolution status",
      description:
        "SOURCE-RESOLVE-1 only. Queries status of a source resolution run. status=pending means the child workflow is still active; status=succeeded returns retained canonical URLs for DevSpace collect; status=failed is fail-closed and includes the terminal failure reason.",
      inputSchema: {
        resolveId: z
          .string()
          .min(1)
          .describe("Resolution identifier returned by source_resolve_start."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async ({ resolveId }) => {
      const statusResult = controller.getResolveStatus(resolveId);
      return {
        content: [
          {
            type: "text" as const,
            text: `SOURCE-RESOLVE-1 status: ${statusResult.status} for ${resolveId}`,
          },
        ],
        structuredContent: statusResult,
      };
    },
  );
}
