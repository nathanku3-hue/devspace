import { registerAppTool } from "@modelcontextprotocol/ext-apps/server";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import * as z from "zod/v4";
import {
  AuditReturnController,
  auditResultSchema,
  HEX_64_PATTERN,
} from "./audit-return.js";

const NO_APP_META = { _meta: {} } as const;

export function registerAuditReturnTools(input: {
  server: McpServer;
  controller: AuditReturnController;
}): void {
  const { server, controller } = input;

  registerAppTool(
    server,
    "audit_start",
    {
      title: "Start evidence-bound audit",
      description:
        "AUDIT-RETURN-1 only. Starts one bounded asynchronous quantitative audit. Generates a one-time 64-hex challenge, binds evidence and packet SHA-256 digests, and launches a fresh ChatGPT Web conversation containing the evidence packet. It does not allow external web search.",
      inputSchema: {
        jobId: z
          .string()
          .min(1)
          .describe("Job identifier to audit (e.g. 20260928-prospective-NVDA)."),
        evidencePacket: z
          .string()
          .min(1)
          .describe("Exact JSON string of the evidence packet to be audited."),
        evidenceSha256: z
          .string()
          .regex(HEX_64_PATTERN)
          .describe("SHA-256 digest of the raw evidence payload."),
        packetSha256: z
          .string()
          .regex(HEX_64_PATTERN)
          .describe("SHA-256 digest of the evidence packet."),
        collectManifest: z
          .string()
          .optional()
          .describe("Relative path to collect manifest for custody binding."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: true,
      },
    },
    async ({
      jobId,
      evidencePacket,
      evidenceSha256,
      packetSha256,
      collectManifest,
    }) => {
      const acknowledgement = await controller.startAudit({
        jobId,
        evidencePacket,
        evidenceSha256,
        packetSha256,
        collectManifest,
      });
      return {
        content: [
          {
            type: "text" as const,
            text: `AUDIT-RETURN-1 audit started for ${jobId}. Use audit_status with returned auditId.`,
          },
        ],
        structuredContent: acknowledgement,
      };
    },
  );

  registerAppTool(
    server,
    "audit_submit",
    {
      title: "Submit evidence-bound audit result",
      description:
        "AUDIT-RETURN-1 only. Invoked exactly once by the launched ChatGPT Web conversation using the one-time challenge. Server verifies the challenge, rejects replays, validates strict audit findings schema, binds evidence hashes, and retains the structured audit with server-owned provenance.",
      inputSchema: {
        challenge: z
          .string()
          .regex(HEX_64_PATTERN)
          .describe("One-time 64-hex challenge generated by audit_start."),
        job_id: z.string().optional().describe("Job identifier being audited."),
        evidence_sha256: z
          .string()
          .regex(HEX_64_PATTERN)
          .optional()
          .describe("SHA-256 digest of raw evidence."),
        packet_sha256: z
          .string()
          .regex(HEX_64_PATTERN)
          .optional()
          .describe("SHA-256 digest of evidence packet."),
        result: auditResultSchema.describe(
          "Strict structured audit output containing summary, findings, and uncertainties.",
        ),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: false,
      },
    },
    async ({ challenge, job_id, evidence_sha256, packet_sha256, result }) => {
      const acknowledgement = controller.submitAudit({
        challenge,
        job_id,
        evidence_sha256,
        packet_sha256,
        result,
      });
      return {
        content: [
          {
            type: "text" as const,
            text: `AUDIT-RETURN-1 audit result submitted successfully for ${acknowledgement.auditId}.`,
          },
        ],
        structuredContent: acknowledgement,
      };
    },
  );

  registerAppTool(
    server,
    "audit_status",
    {
      title: "Query evidence-bound audit status",
      description:
        "AUDIT-RETURN-1 only. Queries the current status of an audit run. When status=succeeded, returns the retained structured audit result, server-owned provenance, and evidence custody linkage for sealing.",
      inputSchema: {
        auditId: z
          .string()
          .min(1)
          .describe("Audit identifier returned by audit_start."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async ({ auditId }) => {
      const statusResult = controller.getAuditStatus(auditId);
      return {
        content: [
          {
            type: "text" as const,
            text: `AUDIT-RETURN-1 status: ${statusResult.status} for ${auditId}`,
          },
        ],
        structuredContent: statusResult,
      };
    },
  );

  registerAppTool(
    server,
    "audit_batch_start",
    {
      title: "Start bounded evidence-bound audit batch",
      description:
        "AUDIT-RETURN-1 only. Starts an asynchronous bounded-concurrency batch of quantitative audits. Launches ChatGPT Web conversations according to bounded concurrency (default: 3, max: 4) without external web search, binds cryptographic evidence hashes, and manages queue pumping.",
      inputSchema: {
        jobs: z
          .array(
            z.object({
              jobId: z
                .string()
                .min(1)
                .describe("Job identifier to audit (e.g. 20260928-prospective-NVDA)."),
              evidencePacket: z
                .string()
                .min(1)
                .describe("Exact JSON string of the evidence packet to be audited."),
              evidenceSha256: z
                .string()
                .regex(HEX_64_PATTERN)
                .describe("SHA-256 digest of raw evidence payload."),
              packetSha256: z
                .string()
                .regex(HEX_64_PATTERN)
                .describe("SHA-256 digest of evidence packet."),
              collectManifest: z
                .string()
                .optional()
                .describe("Relative path to collect manifest for custody binding."),
            }),
          )
          .min(1)
          .max(50)
          .describe("Array of audit jobs to run in this batch."),
        concurrency: z
          .number()
          .int()
          .min(1)
          .max(4)
          .optional()
          .describe("Bounded concurrency limit (default: 3, max: 4)."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: true,
      },
    },
    async ({ jobs, concurrency }) => {
      const batchResult = await controller.startAuditBatch(jobs, { concurrency });
      return {
        content: [
          {
            type: "text" as const,
            text: `AUDIT-RETURN-1 batch started with ${batchResult.total_jobs} jobs (batchId: ${batchResult.batch_id}, concurrency: ${batchResult.concurrency}). Use audit_batch_status to monitor progress.`,
          },
        ],
        structuredContent: batchResult,
      };
    },
  );

  registerAppTool(
    server,
    "audit_batch_status",
    {
      title: "Query evidence-bound audit batch status",
      description:
        "AUDIT-RETURN-1 only. Queries the status and progress of an audit batch. When completed, returns terminal jobs status, failure isolation metrics, and deterministic batch aggregate hash.",
      inputSchema: {
        batchId: z
          .string()
          .min(1)
          .describe("Batch identifier returned by audit_batch_start."),
      },
      ...NO_APP_META,
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async ({ batchId }) => {
      const batchStatus = controller.getAuditBatchStatus(batchId);
      return {
        content: [
          {
            type: "text" as const,
            text: `AUDIT-RETURN-1 batch status: ${batchStatus.status} (${batchStatus.succeeded_jobs}/${batchStatus.total_jobs} succeeded, ${batchStatus.failed_jobs} failed, ${batchStatus.pending_jobs} pending) for ${batchId}`,
          },
        ],
        structuredContent: batchStatus,
      };
    },
  );
}
